-- Custos dos produtos (fichas técnicas). Só gerencial: não baixa estoque.
-- Acrescenta tabelas novas e colunas vazias; não altera nenhum dado existente.

-- Conteúdo de cada embalagem comprada (ex.: 395 g, 900 ml, 30 un). Vazio = o sistema sugere pelo nome.
alter table app.items add column if not exists content_qty double precision check (content_qty is null or content_qty > 0);
alter table app.items add column if not exists content_unit text check (content_unit is null or content_unit in ('g', 'ml', 'un'));

create table if not exists app.products (
  id integer generated by default as identity primary key,
  name text not null,
  category text,
  yield_qty double precision not null default 1 check (yield_qty > 0),
  yield_unit text not null default 'unidades',
  sale_price double precision check (sale_price is null or sale_price >= 0),
  target_margin double precision check (target_margin is null or (target_margin >= 0 and target_margin < 1)),
  indirect_pct double precision check (indirect_pct is null or (indirect_pct >= 0 and indirect_pct <= 5)),
  prep_minutes integer check (prep_minutes is null or prep_minutes >= 0),
  notes text,
  is_active integer not null default 1 check (is_active in (0, 1)),
  created_at text not null default app.agora_texto(),
  updated_at text not null default app.agora_texto()
);
create unique index if not exists products_name_unique on app.products (lower(name));

create table if not exists app.product_lines (
  id integer generated by default as identity primary key,
  product_id integer not null references app.products(id) on delete cascade,
  position integer not null default 0,
  kind text not null check (kind in ('item', 'immediate', 'manual')),
  item_id integer references app.items(id),
  immediate_item_id integer references app.immediate_items(id),
  description text,
  quantity double precision not null check (quantity > 0),
  unit text not null check (unit in ('g', 'kg', 'ml', 'l', 'un', 'emb')),
  per_unit integer not null default 0 check (per_unit in (0, 1)),
  manual_cost double precision check (manual_cost is null or manual_cost >= 0),
  check (
    (kind = 'item' and item_id is not null) or
    (kind = 'immediate' and immediate_item_id is not null) or
    (kind = 'manual' and manual_cost is not null and description is not null)
  )
);
create index if not exists idx_product_lines_product on app.product_lines(product_id);

alter table app.products enable row level security;
alter table app.product_lines enable row level security;
create policy sistema_total on app.products for all to bolos_app using (true) with check (true);
create policy sistema_total on app.product_lines for all to bolos_app using (true) with check (true);
grant select, insert, update, delete on app.products, app.product_lines to bolos_app;
grant usage, select, update on all sequences in schema app to bolos_app;

-- Percentual padrão de custos indiretos (água, luz, gás), editável na tela Custos.
insert into app.meta (key, value) values ('custo_indireto_padrao', '0.10') on conflict (key) do nothing;

-- O ambiente de teste passa a copiar as novas tabelas.
create or replace procedure app_teste.recriar()
language plpgsql set search_path = '' as $$
declare
  t text;
  tabelas text[] := array['meta','periods','period_lock_history','period_snapshots','item_categories',
    'payment_methods','movement_types','immediate_items','items','inventory_opening_balances','inventory_entries',
    'inventory_usages','financial_transactions','account_transfers','suppliers','purchases','purchase_items',
    'products','product_lines'];
  fk record;
  col record;
begin
  foreach t in array app_teste.array_reverse(tabelas) loop
    execute format('drop table if exists app_teste.%I cascade', t);
  end loop;
  foreach t in array tabelas loop
    execute format('create table app_teste.%I (like app.%I including all)', t, t);
    execute format('insert into app_teste.%I overriding system value select * from app.%I', t, t);
  end loop;
  for fk in
    select c.conrelid::regclass::text as tabela, c.conname, pg_get_constraintdef(c.oid) as def
    from pg_constraint c join pg_namespace n on n.oid = c.connamespace
    where n.nspname = 'app' and c.contype = 'f'
  loop
    execute format('alter table app_teste.%I add constraint %I %s',
      split_part(fk.tabela, '.', 2), fk.conname, replace(fk.def, 'app.', 'app_teste.'));
  end loop;
  for col in
    select table_name, column_name from information_schema.columns
    where table_schema = 'app_teste' and column_default like '%agora_texto%'
  loop
    execute format('alter table app_teste.%I alter column %I set default app_teste.agora_texto()', col.table_name, col.column_name);
  end loop;
  foreach t in array tabelas loop
    if t <> 'meta' then
      execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from app_teste.%I), 0) + 1, false)',
        'app_teste.' || t, 'id', t);
    end if;
  end loop;
  execute 'grant select, insert, update, delete on all tables in schema app_teste to bolos_teste';
  execute 'grant usage, select, update on all sequences in schema app_teste to bolos_teste';
end $$;

call app_teste.recriar();
