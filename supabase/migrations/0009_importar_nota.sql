-- Importar compra pela nota (cupom NFC-e pelo QR Code).
-- Só acrescenta colunas vazias e uma tabela nova; não altera dados existentes.

-- CNPJ do fornecedor (só números), para reconhecer o mercado na próxima nota.
alter table app.suppliers add column if not exists document text;
create index if not exists idx_suppliers_document on app.suppliers(document);

-- Chave de acesso da nota: impede registrar a mesma nota duas vezes.
alter table app.purchases add column if not exists access_key text;
create unique index if not exists purchases_access_key_unique on app.purchases(access_key) where access_key is not null;

-- O que fazer com cada produto da nota, aprendido na primeira vez:
-- estoque (com quantas unidades do sistema vêm em cada unidade da nota), uso imediato, casa (retirada) ou não importar.
create table if not exists app.invoice_product_links (
  id integer generated by default as identity primary key,
  supplier_document text not null,
  product_key text not null, -- código do produto na loja, ou a descrição quando não houver código
  description text,
  destination text not null check (destination in ('inventory', 'financial', 'personal', 'skip')),
  item_id integer references app.items(id) on delete set null,
  movement_type_id integer references app.movement_types(id),
  financial_description text,
  qty_factor double precision not null default 1 check (qty_factor > 0),
  updated_at text not null default app.agora_texto(),
  unique (supplier_document, product_key)
);

alter table app.invoice_product_links enable row level security;
create policy sistema_total on app.invoice_product_links for all to bolos_app using (true) with check (true);
grant select, insert, update, delete on app.invoice_product_links to bolos_app;
grant usage, select, update on all sequences in schema app to bolos_app;

create or replace procedure app_teste.recriar()
language plpgsql set search_path = '' as $$
declare
  t text;
  tabelas text[] := array['meta','periods','period_lock_history','period_snapshots','item_categories',
    'payment_methods','movement_types','immediate_items','items','inventory_opening_balances','inventory_entries',
    'inventory_usages','financial_transactions','account_transfers','suppliers','purchases','purchase_items',
    'products','product_lines','product_stages','bank_imports','bank_statement_lines','invoice_product_links'];
  fk record;
  col record;
begin
  foreach t in array app_teste.array_reverse(tabelas) loop
    execute format('drop table if exists app_teste.%I cascade', t);
  end loop;
  foreach t in array tabelas loop
    execute format('create table app_teste.%I (like app.%I including all)', t, t);
    execute format('insert into app_teste.%I overriding system value select * from app.%I', t, t);
  end loop;
  for fk in
    select c.conrelid::regclass::text as tabela, c.conname, pg_get_constraintdef(c.oid) as def
    from pg_constraint c join pg_namespace n on n.oid = c.connamespace
    where n.nspname = 'app' and c.contype = 'f'
  loop
    execute format('alter table app_teste.%I add constraint %I %s',
      split_part(fk.tabela, '.', 2), fk.conname, replace(fk.def, 'app.', 'app_teste.'));
  end loop;
  for col in
    select table_name, column_name from information_schema.columns
    where table_schema = 'app_teste' and column_default like '%agora_texto%'
  loop
    execute format('alter table app_teste.%I alter column %I set default app_teste.agora_texto()', col.table_name, col.column_name);
  end loop;
  foreach t in array tabelas loop
    if t <> 'meta' then
      execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from app_teste.%I), 0) + 1, false)',
        'app_teste.' || t, 'id', t);
    end if;
  end loop;
  execute 'grant select, insert, update, delete on all tables in schema app_teste to bolos_teste';
  execute 'grant usage, select, update on all sequences in schema app_teste to bolos_teste';
end $$;

call app_teste.recriar();
