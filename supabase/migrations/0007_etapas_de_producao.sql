-- Etapas de produção de cada produto (ex.: Dia 1 massa 2 h, Dia 2 banhar e rechear 3 h, Dia 3 embalar 3 h).
-- A agenda vai usar o dia de cada etapa para distribuir as horas, em vez de somar tudo num dia só.
-- Só acrescenta tabela nova; products.prep_minutes passa a guardar a soma das etapas.
create table if not exists app.product_stages (
  id integer generated by default as identity primary key,
  product_id integer not null references app.products(id) on delete cascade,
  position integer not null default 0,
  name text not null,
  day_number integer not null default 1 check (day_number between 1 and 60),
  minutes integer not null check (minutes > 0),
  fixed_time integer not null default 0 check (fixed_time in (0, 1))
);
comment on column app.product_stages.day_number is 'Dia da produção (1 = primeiro dia). Etapas no mesmo dia somam horas naquele dia.';
comment on column app.product_stages.fixed_time is '1 = o tempo não aumenta com o número de receitas (ex.: montar a bancada).';
create index if not exists idx_product_stages_product on app.product_stages(product_id);

alter table app.product_stages enable row level security;
create policy sistema_total on app.product_stages for all to bolos_app using (true) with check (true);
grant select, insert, update, delete on app.product_stages to bolos_app;
grant usage, select, update on all sequences in schema app to bolos_app;

create or replace procedure app_teste.recriar()
language plpgsql set search_path = '' as $$
declare
  t text;
  tabelas text[] := array['meta','periods','period_lock_history','period_snapshots','item_categories',
    'payment_methods','movement_types','immediate_items','items','inventory_opening_balances','inventory_entries',
    'inventory_usages','financial_transactions','account_transfers','suppliers','purchases','purchase_items',
    'products','product_lines','product_stages'];
  fk record;
  col record;
begin
  foreach t in array app_teste.array_reverse(tabelas) loop
    execute format('drop table if exists app_teste.%I cascade', t);
  end loop;
  foreach t in array tabelas loop
    execute format('create table app_teste.%I (like app.%I including all)', t, t);
    execute format('insert into app_teste.%I overriding system value select * from app.%I', t, t);
  end loop;
  for fk in
    select c.conrelid::regclass::text as tabela, c.conname, pg_get_constraintdef(c.oid) as def
    from pg_constraint c join pg_namespace n on n.oid = c.connamespace
    where n.nspname = 'app' and c.contype = 'f'
  loop
    execute format('alter table app_teste.%I add constraint %I %s',
      split_part(fk.tabela, '.', 2), fk.conname, replace(fk.def, 'app.', 'app_teste.'));
  end loop;
  for col in
    select table_name, column_name from information_schema.columns
    where table_schema = 'app_teste' and column_default like '%agora_texto%'
  loop
    execute format('alter table app_teste.%I alter column %I set default app_teste.agora_texto()', col.table_name, col.column_name);
  end loop;
  foreach t in array tabelas loop
    if t <> 'meta' then
      execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from app_teste.%I), 0) + 1, false)',
        'app_teste.' || t, 'id', t);
    end if;
  end loop;
  execute 'grant select, insert, update, delete on all tables in schema app_teste to bolos_teste';
  execute 'grant usage, select, update on all sequences in schema app_teste to bolos_teste';
end $$;

call app_teste.recriar();
