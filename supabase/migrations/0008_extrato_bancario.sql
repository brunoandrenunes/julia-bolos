-- Importação do extrato do banco (Nubank). Cada linha do extrato fica guardada uma vez só
-- (a "impressão digital" evita duplicar ao importar períodos que se sobrepõem) e é resolvida de um jeito:
-- vira lançamento novo, é vinculada a um lançamento/compra/transferência que já existia, ou é ignorada.
-- Só acrescenta tabelas novas; não altera nenhum dado existente.
create table if not exists app.bank_imports (
  id integer generated by default as identity primary key,
  payment_method_id integer not null references app.payment_methods(id),
  file_name text,
  period_start text,
  period_end text,
  opening_balance double precision,
  closing_balance double precision,
  total_in double precision,
  total_out double precision,
  lines_total integer not null default 0,
  lines_new integer not null default 0,
  created_at text not null default app.agora_texto()
);

create table if not exists app.bank_statement_lines (
  id integer generated by default as identity primary key,
  import_id integer references app.bank_imports(id) on delete set null,
  payment_method_id integer not null references app.payment_methods(id),
  movement_date text not null check (movement_date ~ '^\d{4}-\d{2}-\d{2}$'),
  amount double precision not null check (amount <> 0), -- positivo = entrada, negativo = saída
  kind text,
  description text not null,
  counterpart text,
  fingerprint text not null,
  ignored integer not null default 0 check (ignored in (0, 1)),
  financial_transaction_id integer references app.financial_transactions(id) on delete set null,
  purchase_id integer references app.purchases(id) on delete set null,
  transfer_id integer references app.account_transfers(id) on delete set null,
  created_record integer not null default 0 check (created_record in (0, 1)), -- 1 = o lançamento foi criado pela importação
  resolved_at text,
  created_at text not null default app.agora_texto(),
  unique (payment_method_id, fingerprint)
);
create index if not exists idx_bank_lines_date on app.bank_statement_lines(payment_method_id, movement_date);
create index if not exists idx_bank_lines_ft on app.bank_statement_lines(financial_transaction_id);

alter table app.bank_imports enable row level security;
alter table app.bank_statement_lines enable row level security;
create policy sistema_total on app.bank_imports for all to bolos_app using (true) with check (true);
create policy sistema_total on app.bank_statement_lines for all to bolos_app using (true) with check (true);
grant select, insert, update, delete on app.bank_imports, app.bank_statement_lines to bolos_app;
grant usage, select, update on all sequences in schema app to bolos_app;

create or replace procedure app_teste.recriar()
language plpgsql set search_path = '' as $$
declare
  t text;
  tabelas text[] := array['meta','periods','period_lock_history','period_snapshots','item_categories',
    'payment_methods','movement_types','immediate_items','items','inventory_opening_balances','inventory_entries',
    'inventory_usages','financial_transactions','account_transfers','suppliers','purchases','purchase_items',
    'products','product_lines','product_stages','bank_imports','bank_statement_lines'];
  fk record;
  col record;
begin
  foreach t in array app_teste.array_reverse(tabelas) loop
    execute format('drop table if exists app_teste.%I cascade', t);
  end loop;
  foreach t in array tabelas loop
    execute format('create table app_teste.%I (like app.%I including all)', t, t);
    execute format('insert into app_teste.%I overriding system value select * from app.%I', t, t);
  end loop;
  for fk in
    select c.conrelid::regclass::text as tabela, c.conname, pg_get_constraintdef(c.oid) as def
    from pg_constraint c join pg_namespace n on n.oid = c.connamespace
    where n.nspname = 'app' and c.contype = 'f'
  loop
    execute format('alter table app_teste.%I add constraint %I %s',
      split_part(fk.tabela, '.', 2), fk.conname, replace(fk.def, 'app.', 'app_teste.'));
  end loop;
  for col in
    select table_name, column_name from information_schema.columns
    where table_schema = 'app_teste' and column_default like '%agora_texto%'
  loop
    execute format('alter table app_teste.%I alter column %I set default app_teste.agora_texto()', col.table_name, col.column_name);
  end loop;
  foreach t in array tabelas loop
    if t <> 'meta' then
      execute format('select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from app_teste.%I), 0) + 1, false)',
        'app_teste.' || t, 'id', t);
    end if;
  end loop;
  execute 'grant select, insert, update, delete on all tables in schema app_teste to bolos_teste';
  execute 'grant usage, select, update on all sequences in schema app_teste to bolos_teste';
end $$;

call app_teste.recriar();
