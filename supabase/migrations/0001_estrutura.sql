-- Estrutura do sistema Julia Ronsoni Bolos no Supabase.
-- Mesmas tabelas e colunas do banco SQLite original (ids preservados na carga),
-- num schema próprio que não é exposto pela API pública do Supabase.
-- Só o servidor do sistema (papel bolos_app) lê e grava.

create schema if not exists app;
revoke all on schema app from public, anon, authenticated;

-- Datas ficam em texto AAAA-MM-DD (como no sistema original); carimbos de hora em texto UTC.
create or replace function app.agora_texto() returns text
language sql stable set search_path = '' as
$$ select to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

create table app.meta (
  key text primary key,
  value text
);

create table app.periods (
  id integer generated by default as identity primary key,
  year integer not null check (year between 2000 and 2200),
  month integer not null check (month between 1 and 12),
  label text not null,
  opening_bank_balance double precision not null default 0,
  opening_cash_balance double precision not null default 0,
  opening_card_balance double precision not null default 0,
  is_closed integer not null default 0 check (is_closed in (0, 1)),
  closed_at text,
  unique (year, month)
);

create table app.period_lock_history (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  action text not null check (action in ('closed', 'reopened')),
  note text,
  changed_at text not null default app.agora_texto()
);

create table app.period_snapshots (
  id integer generated by default as identity primary key,
  period_id integer not null unique references app.periods(id),
  revenue double precision not null default 0,
  cmv double precision not null default 0,
  inputs double precision not null default 0,
  expenses double precision not null default 0,
  net_profit double precision not null default 0,
  withdrawals double precision not null default 0,
  result double precision not null default 0,
  stock_value double precision,
  available_balance double precision,
  source text not null default 'snapshot'
);

create table app.item_categories (
  id integer generated by default as identity primary key,
  name text not null unique
);

create table app.payment_methods (
  id integer generated by default as identity primary key,
  name text not null unique,
  kind text not null check (kind in ('asset', 'liability'))
);

create table app.movement_types (
  id integer generated by default as identity primary key,
  name text not null unique,
  group_name text not null,
  affects_report integer not null default 1
);

create table app.items (
  id integer generated by default as identity primary key,
  name text not null unique,
  category_id integer references app.item_categories(id),
  unit_size double precision,
  reference_price double precision,
  price_per_kg double precision,
  low_stock_threshold double precision not null default 0,
  notes text,
  is_active integer not null default 1 check (is_active in (0, 1))
);

create table app.inventory_opening_balances (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  item_id integer not null references app.items(id),
  quantity double precision not null default 0,
  total_value double precision not null default 0,
  unique (period_id, item_id)
);

create table app.inventory_entries (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  movement_date text not null check (movement_date ~ '^\d{4}-\d{2}-\d{2}$'),
  payment_method_id integer not null references app.payment_methods(id),
  item_id integer not null references app.items(id),
  quantity double precision not null,
  total_amount double precision not null,
  notes text,
  source text,
  created_at text not null default app.agora_texto()
);

create table app.inventory_usages (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  movement_date text not null check (movement_date ~ '^\d{4}-\d{2}-\d{2}$'),
  item_id integer not null references app.items(id),
  quantity double precision not null,
  notes text,
  source text,
  created_at text not null default app.agora_texto()
);

create table app.financial_transactions (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  movement_date text not null check (movement_date ~ '^\d{4}-\d{2}-\d{2}$'),
  payment_method_id integer not null references app.payment_methods(id),
  movement_type_id integer not null references app.movement_types(id),
  description text not null,
  amount double precision not null,
  notes text,
  item_id integer references app.items(id),
  source text,
  created_at text not null default app.agora_texto()
);

create table app.account_transfers (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  movement_date text not null check (movement_date ~ '^\d{4}-\d{2}-\d{2}$'),
  from_payment_method_id integer not null references app.payment_methods(id),
  to_payment_method_id integer not null references app.payment_methods(id),
  amount double precision not null,
  description text not null,
  notes text,
  source text,
  created_at text not null default app.agora_texto()
);

create table app.suppliers (
  id integer generated by default as identity primary key,
  name text not null,
  contact text,
  notes text,
  is_active integer not null default 1 check (is_active in (0, 1)),
  created_at text not null default app.agora_texto()
);
-- Igual ao COLLATE NOCASE do SQLite: não permite o mesmo nome com maiúsculas diferentes.
create unique index suppliers_name_unique on app.suppliers (lower(name));

create table app.purchases (
  id integer generated by default as identity primary key,
  period_id integer not null references app.periods(id),
  purchase_date text not null check (purchase_date ~ '^\d{4}-\d{2}-\d{2}$'),
  supplier_id integer not null references app.suppliers(id),
  payment_method_id integer not null references app.payment_methods(id),
  invoice_number text,
  notes text,
  created_at text not null default app.agora_texto()
);

create table app.purchase_items (
  id integer generated by default as identity primary key,
  purchase_id integer not null references app.purchases(id),
  destination text not null check (destination in ('inventory', 'financial')),
  item_id integer references app.items(id),
  description text not null,
  quantity double precision not null default 1,
  total_amount double precision not null,
  movement_type_id integer references app.movement_types(id),
  inventory_entry_id integer unique references app.inventory_entries(id),
  financial_transaction_id integer unique references app.financial_transactions(id)
);

create index idx_purchases_period on app.purchases(period_id);
create index idx_purchases_supplier on app.purchases(supplier_id);
create index idx_purchase_items_purchase on app.purchase_items(purchase_id);
create index idx_inventory_entries_period on app.inventory_entries(period_id);
create index idx_inventory_entries_item on app.inventory_entries(item_id);
create index idx_inventory_usages_period on app.inventory_usages(period_id);
create index idx_inventory_usages_item on app.inventory_usages(item_id);
create index idx_financial_transactions_period on app.financial_transactions(period_id);
create index idx_account_transfers_period on app.account_transfers(period_id);
create index idx_opening_balances_item on app.inventory_opening_balances(item_id);
create index idx_lock_history_period on app.period_lock_history(period_id);
create index idx_items_category on app.items(category_id);
create index idx_purchases_payment on app.purchases(payment_method_id);
create index idx_purchase_items_item on app.purchase_items(item_id);
create index idx_purchase_items_type on app.purchase_items(movement_type_id);
create index idx_inventory_entries_payment on app.inventory_entries(payment_method_id);
create index idx_financial_transactions_payment on app.financial_transactions(payment_method_id);
create index idx_financial_transactions_type on app.financial_transactions(movement_type_id);
create index idx_financial_transactions_item on app.financial_transactions(item_id);
create index idx_account_transfers_from on app.account_transfers(from_payment_method_id);
create index idx_account_transfers_to on app.account_transfers(to_payment_method_id);

-- Papel usado pelo servidor do sistema: só lê e grava dados, não altera estrutura.
-- A senha é definida à parte (fora do repositório).
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'bolos_app') then
    create role bolos_app login noinherit;
  end if;
end $$;
alter role bolos_app set search_path = app;
grant usage on schema app to bolos_app;
grant select, insert, update, delete on all tables in schema app to bolos_app;
grant usage, select, update on all sequences in schema app to bolos_app;
grant execute on function app.agora_texto() to bolos_app;

-- Proteção extra: RLS ligado; só o papel do sistema tem acesso.
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = 'app' loop
    execute format('alter table app.%I enable row level security', t.tablename);
    execute format('create policy sistema_total on app.%I for all to bolos_app using (true) with check (true)', t.tablename);
  end loop;
end $$;
